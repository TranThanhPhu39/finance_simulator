PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS runs(id TEXT PRIMARY KEY,status TEXT NOT NULL,created_at TEXT NOT NULL,payload TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS run_steps(run_id TEXT NOT NULL REFERENCES runs(id),ordinal INTEGER NOT NULL,payload TEXT NOT NULL,PRIMARY KEY(run_id,ordinal));
CREATE TABLE IF NOT EXISTS assertions(run_id TEXT NOT NULL REFERENCES runs(id),ordinal INTEGER NOT NULL,payload TEXT NOT NULL,PRIMARY KEY(run_id,ordinal));
CREATE TABLE IF NOT EXISTS transaction_evidence(run_id TEXT NOT NULL REFERENCES runs(id),ordinal INTEGER NOT NULL,payload TEXT NOT NULL,PRIMARY KEY(run_id,ordinal));
CREATE TABLE IF NOT EXISTS requests(key TEXT PRIMARY KEY,fingerprint TEXT NOT NULL,run_ids TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY,value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS locks(key TEXT PRIMARY KEY,owner TEXT NOT NULL,pid INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS governance(id TEXT PRIMARY KEY,payload TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS runs_created ON runs(created_at DESC);
PRAGMA user_version=1;
